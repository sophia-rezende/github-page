CREATE DATABASE IF NOT EXISTS LOCADORA;

USE LOCADORA;

CREATE TABLE IF NOT EXISTS LOCADORA.CLIENTE
(
	ID_CLIENTE INT,
    NOME_COMPLETO VARCHAR(100),
    NUM_TELEFONE VARCHAR(11),
    DESC_EMAIL VARCHAR(100),
    DATA_NASCIMENTO DATE,
    PRIMARY KEY (ID_CLIENTE)
);

