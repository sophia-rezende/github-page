CREATE TABLE IF NOT EXISTS LOCADORA.CARROS
(
	ID_CARROS INT,
    MODELO VARCHAR(50),
    MARCA VARCHAR(30),
    ANO YEAR,
    COR VARCHAR(20),
    PLACA VARCHAR(10) NOT NULL,
    VALOR DECIMAL(10,2),
    PRIMARY KEY (ID_CARROS)
);


                             